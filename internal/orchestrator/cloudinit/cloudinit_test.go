func TestK6RemoteWriteURL(t *testing.T) {
	in := validInput()
	got, err := in.K6RemoteWriteURL()
	if err != nil {
		t.Fatalf("K6RemoteWriteURL: %v", err)
	}
	want := "https://ddos-dce-eastus-xyz.eastus-1.handler.control.monitor.azure.com" +
		"/dataCollectionRules/dcr-0123456789abcdef0123456789abcdef" +
		"/streams/Microsoft-PrometheusMetrics/api/v1/write?api-version=2023-04-24"
	if got != want {
		t.Errorf("URL:\n got  %s\n want %s", got, want)
	}
}

