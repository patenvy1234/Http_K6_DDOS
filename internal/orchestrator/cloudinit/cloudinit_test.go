func TestRenderProducesValidYAMLAndExpectedContent(t *testing.T) {
	out, err := Render(validInput())
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	yamlText := string(out)

	if !strings.HasPrefix(yamlText, "#cloud-config\n") {
		t.Errorf("missing #cloud-config header; first line: %q",
			strings.SplitN(yamlText, "\n", 2)[0])
	}

	mustContain := []string{
		"net.ipv4.ip_local_port_range = 1024 65535",
		"*    soft    nofile    1048576",
		"DDOS_RUN_ID=ab12cd34",
		"ddos-imds-token",
		"K6_PROMETHEUS_RW_BEARER_TOKEN=",
		`K6_VERSION="${DDOS_K6_VERSION:-0.58.0}"`,
		"systemctl enable --now ddos-worker.service",
		"Description=DDOS - refresh Entra access token",
		"Description=DDOS k6 load-generation worker",
		"Type=notify",
		"Requires=ddos-token-refresh.service",
		"systemd-notify --ready",
		`jq -er '.access_token | select(type == "string" and length > 0)'`,
		`cp -a "${STAGE}/." "${DEST_DIR}/"`,
		"K6_PROMETHEUS_RW_SERVER_URL=https://ddos-dce-eastus-xyz",
		"ssh-rsa AAAAB3NzaC1yc2EAAAADAQABAAABAQ== ddos@test",
	}
	for _, s := range mustContain {
		if !strings.Contains(yamlText, s) {
			t.Errorf("rendered output missing %q", s)
		}
	}

	var dummy any
	if err := yaml.Unmarshal(out, &dummy); err != nil {
		t.Fatalf("YAML parse failed: %v\n---\n%s", err, yamlText)
	}
}

